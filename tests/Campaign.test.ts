import test from 'node:test';
import assert from 'node:assert/strict';
import {Campaign,MISSIONS} from '../src/game/campaign/Campaign.ts';
import {MissionPuzzle} from '../src/game/education/MissionPuzzles.ts';

test('campaign has ten authored, distinct actions and ordered chapters',()=>{
  assert.equal(MISSIONS.length,10);
  assert.equal(new Set(MISSIONS.map(m=>m.kind)).size,10);
  assert.equal(new Set(MISSIONS.map(m=>m.title)).size,10);
  const campaign=new Campaign();
  assert.equal(campaign.advance('collect'),null);
  assert.equal(campaign.advance('circuit')?.kind,'collect');
  assert.equal(campaign.advance('collect')?.kind,'memory');
  assert.equal(campaign.advance('memory')?.kind,'clear');
  assert.equal(campaign.advance('clear'),null);
  assert.equal(campaign.markTarget('clear',0),true);
  assert.equal(campaign.markTarget('clear',0),false);
  assert.equal(campaign.markTarget('clear',1),true);
  assert.equal(campaign.markTarget('clear',2),true);
  assert.equal(campaign.steps,3);
  assert.equal(campaign.advance('clear')?.kind,'patrol');
  assert.equal(campaign.visitPatrol({x:4.2,z:-14},'robot'),false);
  assert.equal(campaign.visitPatrol({x:4.2,z:-21},'vehicle'),false);
  for(const z of [-14,-21,-25])assert.equal(campaign.visitPatrol({x:4.2,z},'vehicle'),true);
  assert.equal(campaign.steps,3);
  assert.equal(campaign.advance('patrol')?.kind,'count');
  assert.equal(campaign.advance('count')?.kind,'mirrors');
  assert.equal(campaign.advance('mirrors')?.kind,'drones');
  for(const id of [0,1,2])assert.equal(campaign.markTarget('drones',id),true);
  assert.equal(campaign.advance('drones')?.kind,'shapes');
  assert.equal(campaign.advance('shapes')?.kind,'finale');
  assert.equal(campaign.mission.kind,'finale');
  assert.equal(campaign.visitFinale({x:4.2,z:-21},'robot'),false);
  assert.equal(campaign.visitFinale({x:4.2,z:-21},'vehicle'),true);
  assert.equal(campaign.visitFinale({x:0,z:-29},'robot'),true);
  assert.equal(campaign.done,true);
});
test('child-friendly puzzles allow retry without losing progress elsewhere',()=>{
  const memory=new MissionPuzzle('memory');
  assert.equal(memory.choose('🔴').complete,false);
  for(const value of memory.sequence)memory.choose(value);
  assert.equal(memory.complete,true);
  const count=new MissionPuzzle('count');
  for(const value of ['0','1','2','3','4'])count.choose(value);
  assert.equal(count.submitCount().complete,false);
  count.choose('4');
  assert.equal(count.submitCount().complete,true);
  const mirrors=new MissionPuzzle('mirrors');
  mirrors.choose('0');mirrors.choose('2');
  assert.equal(mirrors.complete,true);
  const shapes=new MissionPuzzle('shapes');
  shapes.choose('●');shapes.choose('★');shapes.choose('●');
  assert.equal(shapes.complete,true);
});
